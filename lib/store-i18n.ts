export const dictionaries: Record<Lang, Dict> = { fr, ar };
export type StoreCopy = Dict;
export const getCopy = (lang: Lang): StoreCopy => dictionaries[lang];

export const fill = (template: string, values: Record<string, string | number>) =>
  Object.entries(values).reduce((text, [key, value]) => text.replaceAll(`{${key}}`, String(value)), template);

/** Builds a path in the right language: French has no prefix, Arabic lives under /ar. */
export const localePath = (lang: Lang, path = "/") => {
  const clean = path.startsWith("/") ? path : `/${path}`;
  if (lang === "fr") return clean;
  return clean === "/" ? "/ar" : `/ar${clean}`;
};
