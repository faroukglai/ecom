export type DashCopy = (typeof dashCopy)[DashLang];

export function fill(template: string, values: Record<string, string | number>) {
  return Object.entries(values).reduce((text, [key, value]) => text.replaceAll(`{${key}}`, String(value)), template);
}

export function orderStatusLabel(t: DashCopy, status: string) {
  if (status === "new") return t.statusNew;
  if (status === "confirmed") return t.statusConfirmed;
  if (status === "shipped") return t.statusShipped;
  if (status === "delivered") return t.statusDelivered;
  if (status === "cancelled") return t.statusCancelled;
  return status;
}

export function visibilityLabel(t: DashCopy, visibility: string) {
  if (visibility === "published") return t.visPublished;
  if (visibility === "scheduled") return t.visScheduled;
  if (visibility === "hidden") return t.visHidden;
  return visibility;
}

export function parseDashLang(value: string | undefined | null): DashLang {
  return value === "ar" ? "ar" : "en";
}

export function dashMoney(amount: number, lang: DashLang) {
  const formatted = new Intl.NumberFormat(lang === "ar" ? "ar-TN" : "en", { maximumFractionDigits: 2 }).format(amount);
  return lang === "ar" ? `${formatted} د.ت` : `${formatted} TND`;
}
